          <h3>Enrollment Procedure</h3>
          <ol class="steps">
            <li>Submit all original credentials to the Admissions Office, including the approved accreditation of courses.</li>
            <li>Pay the non-refundable down payment of <strong>Php 5,000</strong>.</li>
            <li>Using your student number (as <em>USERNAME</em>) and your assigned temporary password, access your eLearning account at <a class="link" href="https://learn.adamson.edu.ph" target="_blank" rel="noopener">learn.adamson.edu.ph</a>.</li>
            <li>Go to <strong>Subject Enlistment</strong> &rarr; <strong>Proceed to Subject Enlistment</strong>.</li>
            <li>From <strong>Pre-Advised Subjects</strong>, choose schedules/sections for each subject. Add, edit, or delete as needed, then <strong>Save</strong>.</li>
            <li>Print your <strong>Certificate of Enrollment</strong> (with Assessment of Fees).</li>
            <li>Proceed to the <strong>ID Section</strong> for ID processing.</li>
            <li>Proceed to the <strong>University Store</strong> to purchase the school uniform.</li>
            <li>Attend the <strong>Freshmen/Transferee Orientation</strong> scheduled by the Office for Student Affairs.</li>
          </ol>
          <div class="note">
